"""
ShopManager OS — Invoice Number Generator

Purpose:
    Generates unique, sequential invoice numbers in a safe, atomic manner.
    Invoice numbers are ALWAYS generated by the backend — never by the frontend.

Responsibilities:
    - Generate the next invoice number for a given prefix and year
    - Use SELECT FOR UPDATE to prevent duplicate numbers under concurrent requests
    - Ensure the sequence is part of the same transaction as invoice creation

Dependencies:
    - SQLAlchemy (AsyncSession)
    - backend.modules.invoices.models.InvoiceSequence (defined in Phase 3)

Usage:
    from backend.shared.utils.invoice_numbering import InvoiceNumberingService

    # Inside an invoice creation transaction:
    async with session.begin():
        invoice_no = await InvoiceNumberingService.get_next_number(session, prefix="INV")
        # invoice_no = "INV-00001" on first invoice, "INV-00002" on second, etc.

Notes:
    WHY SELECT FOR UPDATE?
    - Without locking, two simultaneous invoice creation requests could both read
      the same last_number (e.g., 5) and both generate "INV-00006".
    - SELECT FOR UPDATE locks the row until the transaction commits.
    - This ensures strict sequential numbering even under concurrent requests.

    WHY is the sequence reset by year?
    - Many Indian businesses restart invoice numbering each financial year.
    - The invoice_sequence table stores one row per (prefix, year) combination.
    - This is configurable: financial year reset can be added later.

    Number Format:
    - "INV-00001" → prefix="INV", number=1, padded to 5 digits
    - "INV-00002" → prefix="INV", number=2
    - Custom prefix like "BILL" → "BILL-00001"
"""

import logging
from datetime import datetime
from typing import Any

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

logger = logging.getLogger(__name__)


class InvoiceNumberingService:
    """
    Service for generating unique, sequential invoice numbers.

    This service is called ONLY inside invoice creation transactions.
    It must NEVER be called outside of a transaction.
    """

    def __init__(self, session: AsyncSession, settings_repo: Any = None):
        self.session = session
        self.settings_repo = settings_repo

    async def generate_next_invoice_number(self) -> str:
        """
        Generates next sequential number honoring prefix from Settings.
        """
        prefix = "INV"
        if self.settings_repo:
            try:
                settings_val = await self.settings_repo.get_settings()
                if settings_val and isinstance(settings_val, dict):
                    prefix = settings_val.get("invoice", {}).get("prefix", "INV") or "INV"
            except Exception as e:
                logger.warning(f"Could not load invoice prefix from settings: {e}")
        return await self.get_next_number(self.session, prefix=prefix)

    @staticmethod
    async def get_next_number(
        session: AsyncSession,
        prefix: str = "INV",
        year: int | None = None,
    ) -> str:
        """
        Generates the next sequential invoice number.

        IMPORTANT: This method must be called inside an active transaction.
        The SELECT FOR UPDATE lock is released when the transaction commits.

        Steps:
            1. Determine the current year (or use provided year).
            2. Find the invoice_sequence row for (prefix, year) — create if missing.
            3. Lock the row with SELECT FOR UPDATE.
            4. Increment last_number by 1.
            5. Format as "{PREFIX}-{number:05d}" (e.g., "INV-00001").
            6. Return the formatted invoice number.

        @param session: Active AsyncSession (must be inside a transaction)
        @param prefix: Invoice number prefix (default: "INV")
        @param year: The year for this sequence (default: current calendar year)
        @returns str: Formatted invoice number (e.g., "INV-00001")
        """
        # NOTE: This import is here to avoid circular imports.
        # The InvoiceSequence model is defined in the invoices module (Phase 3).
        # Until Phase 3 is implemented, this method cannot be called.
        # It is included here as the architectural placeholder.
        try:
            from backend.modules.invoices.models import InvoiceSequence
        except ImportError:
            raise NotImplementedError(
                "InvoiceSequence model is not yet implemented. "
                "This is part of Phase 3 (Billing Engine)."
            )

        current_year = year or datetime.now().year

        # Step 1: Try to find the existing sequence row for this prefix + year.
        # WITH FOR UPDATE locks the row to prevent concurrent reads.
        stmt = (
            select(InvoiceSequence)
            .where(
                InvoiceSequence.prefix == prefix,
                InvoiceSequence.year == current_year,
            )
            .with_for_update()  # 🔒 Row-level lock — prevents duplicate numbers
        )
        result = await session.execute(stmt)
        sequence = result.scalar_one_or_none()

        if sequence is None:
            # Step 2: First invoice of this prefix + year.
            # Create the sequence row starting at 1.
            sequence = InvoiceSequence(
                prefix=prefix,
                year=current_year,
                last_number=1,
            )
            session.add(sequence)
            next_number = 1
        else:
            # Step 3: Increment the existing sequence.
            sequence.last_number += 1
            next_number = sequence.last_number

        # Step 4: Format the invoice number.
        # "INV-00001", "INV-00002", etc. (5-digit zero-padded)
        invoice_no = f"{prefix}-{next_number:05d}"

        logger.info(f"Generated invoice number: {invoice_no}")
        return invoice_no

    @staticmethod
    def preview_next_number(prefix: str, current_last: int, year: int | None = None) -> str:
        """
        Returns a preview of what the next invoice number would be, without
        consuming the sequence. Used for display purposes only (e.g., billing form).

        @param prefix: Invoice number prefix
        @param current_last: The current last_number value from the sequence table
        @param year: The year (unused in current format, but kept for future use)
        @returns str: The next invoice number that would be generated
        """
        return f"{prefix}-{current_last + 1:05d}"
